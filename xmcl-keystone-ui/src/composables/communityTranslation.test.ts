import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest'
import { createCommunityTranslator } from './communityTranslation'

describe('optional community translations', () => {
  beforeEach(() => vi.useFakeTimers())
  afterEach(() => vi.useRealTimers())
  const endpoint = 'https://example.invalid'
  it.each([403, 429, 500])('soft-falls back for HTTP %i with one safe diagnostic and cooldown', async (status) => {
    const fetch = vi.fn().mockResolvedValue(new Response('private response', { status }))
    const report = vi.fn()
    const get = createCommunityTranslator(fetch, report)
    const a = get(endpoint, 'modrinth', 'private-id', 'zh-CN')
    const b = get(endpoint, 'modrinth', 'private-id', 'zh-CN')
    expect(a).toBe(b)
    await vi.advanceTimersByTimeAsync(250)
    expect(await a).toBe('')
    expect(await get(endpoint, 'modrinth', 'private-id', 'zh-CN')).toBe('')
    expect(fetch).toHaveBeenCalledTimes(1)
    expect(report).toHaveBeenCalledTimes(1)
    expect(report.mock.calls[0][0]).toMatchObject({ status, provider: 'modrinth' })
    expect(JSON.stringify(report.mock.calls)).not.toMatch(/private|translation\?/)
    fetch.mockResolvedValue(new Response('translated'))
    await vi.advanceTimersByTimeAsync(60_000)
    const retry = get(endpoint, 'modrinth', 'private-id', 'zh-CN')
    await vi.advanceTimersByTimeAsync(250)
    expect(await retry).toBe('translated')
  })
  it('isolates locales and providers, preserves successes and coalesces inflight requests', async () => {
    const fetch = vi.fn().mockImplementation(async () => new Response('translated'))
    const get = createCommunityTranslator(fetch)
    const a = get(endpoint, 'modrinth', 1, 'zh-CN')
    const b = get(endpoint, 'modrinth', 1, 'zh-CN')
    const c = get(endpoint, 'modrinth', 1, 'ja')
    const d = get(endpoint, 'curseforge', 1, 'zh-CN')
    await vi.advanceTimersByTimeAsync(250)
    expect(await Promise.all([a, b, c, d])).toEqual(Array(4).fill('translated'))
    expect(fetch).toHaveBeenCalledTimes(3)
    expect(fetch.mock.calls[1][1].headers).toEqual({ 'Accept-Language': 'ja' })
  })
  it('handles network and response-body failures without exposing native messages', async () => {
    const fetch = vi.fn().mockRejectedValue(new TypeError('secret URL and user text'))
    const report = vi.fn()
    const get = createCommunityTranslator(fetch, report)
    const a = get(endpoint, 'modrinth', 1, 'zh-CN')
    await vi.advanceTimersByTimeAsync(250)
    expect(await a).toBe('')
    expect(report.mock.calls[0][0].message).toContain('network')
    fetch.mockResolvedValue({ ok: true, status: 200, text: () => Promise.reject(new Error('secret body')) })
    const b = get(endpoint, 'modrinth', 1, 'ja')
    await vi.advanceTimersByTimeAsync(250)
    expect(await b).toBe('')
    expect(report.mock.calls[1][0].message).not.toContain('secret')
  })
  it('does not let a failed locale suppress another language', async () => {
    const fetch = vi.fn().mockResolvedValueOnce(new Response('', { status: 503 }))
      .mockResolvedValueOnce(new Response('日本語'))
    const get = createCommunityTranslator(fetch, vi.fn())
    const first = get(endpoint, 'modrinth', 1, 'zh-CN')
    await vi.advanceTimersByTimeAsync(250)
    expect(await first).toBe('')
    const second = get(endpoint, 'modrinth', 1, 'ja')
    await vi.advanceTimersByTimeAsync(250)
    expect(await second).toBe('日本語')
    expect(await get(endpoint, 'modrinth', 1, 'zh-CN')).toBe('')
    expect(fetch).toHaveBeenCalledTimes(2)
  })
  it('supplies a bounded timeout signal and soft-falls back on abort', async () => {
    const timeout = vi.spyOn(AbortSignal, 'timeout').mockReturnValue(AbortSignal.abort())
    const fetch = vi.fn().mockImplementation(async (_url, options) => {
      options.signal.throwIfAborted()
    })
    const get = createCommunityTranslator(fetch as unknown as typeof globalThis.fetch, vi.fn())
    const result = get(endpoint, 'curseforge', 1, 'zh-CN')
    await vi.advanceTimersByTimeAsync(250)
    expect(await result).toBe('')
    expect(timeout).toHaveBeenCalledWith(10_000)
    timeout.mockRestore()
  })

  it('survives a throwing reporter, releases pending and recovers after cooldown', async () => {
    const fetch = vi.fn().mockResolvedValueOnce(new Response('', { status: 503 }))
      .mockResolvedValueOnce(new Response('recovered'))
    const report = vi.fn(() => { throw new Error('diagnostics unavailable') })
    const get = createCommunityTranslator(fetch, report)
    const failed = get(endpoint, 'modrinth', 1, 'zh-CN')
    await vi.advanceTimersByTimeAsync(250)
    expect(await failed).toBe('')
    expect(await get(endpoint, 'modrinth', 1, 'zh-CN')).toBe('')
    await vi.advanceTimersByTimeAsync(60_000)
    const retry = get(endpoint, 'modrinth', 1, 'zh-CN')
    expect(retry).not.toBe(failed)
    await vi.advanceTimersByTimeAsync(250)
    expect(await retry).toBe('recovered')
    expect(fetch).toHaveBeenCalledTimes(2)
    expect(report).toHaveBeenCalledTimes(1)
  })

})
